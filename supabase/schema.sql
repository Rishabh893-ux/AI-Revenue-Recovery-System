-- ReviveAI database schema.
-- Run once in Supabase: SQL Editor -> New query -> paste -> Run.
-- Safe to re-run: every statement is "if not exists".

create table if not exists carts (
  id text primary key,                      -- cartId generated by the frontend
  customer_name text,
  customer_email text,
  customer_phone text,
  total_amount numeric,                     -- computed server-side from the catalog
  status text default 'active',             -- active | abandoned | paid
  razorpay_order_id text,
  razorpay_payment_id text,
  payment_status text,                      -- pending | paid | failed
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists cart_items (
  id uuid primary key default gen_random_uuid(),
  cart_id text references carts(id) on delete cascade,
  product_id text,
  name text,
  price numeric,
  quantity integer
);

create table if not exists payment_events (
  id uuid primary key default gen_random_uuid(),
  cart_id text references carts(id) on delete set null,
  order_id text,
  payment_id text,
  status text,                              -- created | verified | captured | failed
  amount numeric,
  created_at timestamptz default now()
);

create table if not exists agent_actions (
  id uuid primary key default gen_random_uuid(),
  cart_id text references carts(id) on delete set null,
  customer_name text,
  amount numeric,
  problem text,                             -- Abandoned Cart | Payment Failed
  ai_action text,                           -- Email Recovery | Discount Offer | ...
  status text,                              -- Pending | Recovered | Lost
  created_at timestamptz default now()
);

-- RLS on with no policies: the public anon key can't read or write these
-- tables. The backend uses the service_role key, which bypasses RLS.
alter table carts enable row level security;
alter table cart_items enable row level security;
alter table payment_events enable row level security;
alter table agent_actions enable row level security;
